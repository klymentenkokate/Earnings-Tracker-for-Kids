// ─────────────────────────────────────────────────────────────
// LA ESCALERA DEL MILLÓN — TV-style ladder quiz in the Quizzes tab (28 Nov 2026).
// 10 questions of rising difficulty (one per rung, picked from MI_BANK by level, unseen first), 4 answers,
// "¿respuesta final?", suspense, reveal, the host's fun fact. Two safe rungs. Three lifelines: 50:50, the audience
// (simulated poll that gets less sure as questions get harder) and the phone call (a friend's hint + 30 s to ask
// someone at home). You can walk away with what you have. Points only, no money.
// Bank + host lines: mi/bank.js (MI_BANK, MI_LINES). Voices: mi/voice.js (MI_VOICE) + mi/au/. Progress: state.mi.
// Generated by Documents/school/millon/build_mi.py. Sounds are synthesised (Web Audio), nothing copied.
// ─────────────────────────────────────────────────────────────
const MI_RUNGS = [100, 200, 500, 1000, 2000, 5000, 10000, 50000, 250000, 1000000];
const MI_SAFE = [3, 6];             // rung indexes that are safe (1.000 and 10.000)
let miG = null, miAudio = null, miT = [], miAC = null, miMute = false;

const miFmt = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '.');
const miE = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const miQ = id => MI_BANK.find(q => q.id === id);
const MI_L = 'ABCD';
function miState() {
  if (!state.mi) state.mi = { seen: [], games: 0, records: [], name: '' };
  return state.mi;
}
function miLater(fn, ms) { miT.push(setTimeout(fn, ms)); }
function miClear() { miT.forEach(clearTimeout); miT = []; }

// ---------- sound: tiny synth, original cues ----------
function miTone(seq, type = 'sine', vol = .18) {
  if (miMute) return;
  try {
    miAC = miAC || new (window.AudioContext || window.webkitAudioContext)();
    let t = miAC.currentTime + .02;
    seq.forEach(([f, d, f2]) => {
      const o = miAC.createOscillator(), g = miAC.createGain();
      o.type = type; o.frequency.setValueAtTime(f, t); if (f2) o.frequency.exponentialRampToValueAtTime(f2, t + d);
      g.gain.setValueAtTime(0, t); g.gain.linearRampToValueAtTime(vol, t + .02); g.gain.exponentialRampToValueAtTime(.001, t + d);
      o.connect(g).connect(miAC.destination); o.start(t); o.stop(t + d + .05); t += d * .85;
    });
  } catch (e) {}
}
const MI_SFX = {
  start: () => miTone([[392, .18], [523, .18], [659, .18], [784, .5]], 'triangle', .2),
  lock: () => miTone([[440, .12], [330, .3]], 'square', .07),
  tense: () => miTone([[110, .5], [116, .5], [110, .5], [123, .7]], 'sawtooth', .05),
  ok: () => miTone([[523, .12], [659, .12], [784, .12], [1047, .45]], 'triangle', .22),
  bad: () => miTone([[220, .3, 180], [160, .6, 110]], 'sawtooth', .1),
  ring: () => miTone([[880, .12], [988, .12], [880, .12], [988, .12], [0.01, .3], [880, .12], [988, .12], [880, .12], [988, .12]], 'sine', .12),
  whoosh: () => miTone([[300, .35, 1200]], 'sine', .08),
  win: () => miTone([[523, .15], [659, .15], [784, .15], [1047, .25], [784, .12], [1047, .6]], 'triangle', .22),
};
function miSfx(k) { MI_SFX[k] && MI_SFX[k](); }

// ---------- voice ----------
function miStop() {
  if (miAudio) { miAudio.onended = null; miAudio.pause(); miAudio = null; }
  if (window.speechSynthesis) speechSynthesis.cancel();
}
function miSay(key, text, done) {
  miStop();
  if (miMute) { done && miLater(done, 600); return; }
  const f = window.MI_VOICE && MI_VOICE[key];
  if (f) {
    const a = new Audio(`mi/au/${f}`); miAudio = a;
    a.onended = () => { if (miAudio === a) { miAudio = null; done && done(); } };
    a.play().catch(() => { if (miAudio === a) done && miLater(done, 1200); });
    return;
  }
  if (text && window.speechSynthesis && window.SpeechSynthesisUtterance) {
    const u = new SpeechSynthesisUtterance(text); u.lang = 'es-ES';
    const v = speechSynthesis.getVoices().find(v => /^es(-|_)ES/i.test(v.lang)); if (v) u.voice = v;
    u.onend = () => done && done(); speechSynthesis.speak(u); return;
  }
  done && miLater(done, 1500);
}
const miLine = (k, done) => miSay('_:' + k, MI_LINES[k], done);

// ---------- shell ----------
function miRoot() {
  let r = document.getElementById('mi-root');
  if (!r) { r = document.createElement('div'); r.id = 'mi-root'; document.body.appendChild(r); }
  return r;
}
function miShow(html) {
  const r = miRoot(); r.style.display = 'block';
  r.innerHTML = `<div class="mi-beams"><i></i><i></i><i></i></div>
    <div class="mi-top"><button class="mi-ic" onclick="miToggleMute()" title="Sonido">${miMute ? '🔇' : '🔊'}</button>
    <button class="mi-ic" onclick="miFull()" title="Pantalla completa">📺</button><button class="mi-ic" onclick="miClose()" title="Salir">✕</button></div>` + html;
  if (window.twemoji) twemoji.parse(r, { folder: 'svg', ext: '.svg' });
}
function miClose() {
  if (miG && miG.phase !== 'end' && !confirm('¿Salir? Se perderá la partida.')) return;
  miStop(); miClear(); miG = null;
  const r = document.getElementById('mi-root'); if (r) { r.style.display = 'none'; r.innerHTML = ''; }
  if (document.fullscreenElement) document.exitFullscreen().catch(() => {});
  if (typeof buildCategoryScreen === 'function') buildCategoryScreen();
}
function miFull() {
  const r = miRoot();
  if (document.fullscreenElement) document.exitFullscreen().catch(() => {}); else if (r.requestFullscreen) r.requestFullscreen().catch(() => {});
}
function miToggleMute() {
  miMute = !miMute; if (miMute) miStop();
  document.querySelectorAll('#mi-root .mi-top .mi-ic')[0].textContent = miMute ? '🔇' : '🔊';
}

