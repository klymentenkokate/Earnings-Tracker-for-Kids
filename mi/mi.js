// ---------- game ----------
function miPick() {
  const seen = new Set(miState().seen), ids = [];
  for (let l = 1; l <= 10; l++) {
    const all = MI_BANK.filter(q => q.l === l), fresh = all.filter(q => !seen.has(q.id));
    const pool = fresh.length ? fresh : all;
    ids.push(pool[Math.floor(Math.random() * pool.length)].id);
  }
  return ids;
}
function miStart() {
  const st = miState(), name = (document.getElementById('mi-name').value || '').trim() || 'Concursante';
  st.name = name; save();
  miG = { name, qs: miPick(), i: 0, used: {}, hidden: [], sel: null, phase: 'q', poll: null };
  miSfx('start');
  miRender();
  miLine('hola', () => miAsk());
}
function miAsk() {
  const q = miQ(miG.qs[miG.i]);
  miG.hidden = []; miG.sel = null; miG.phase = 'q'; miG.poll = null;
  miRender();
  miSfx('whoosh');
  miLine('r' + (miG.i + 1), () => miSay(q.id + ':q', q.q + ' ' + q.o.map((o, k) => MI_L[k] + ': ' + o).join('. ')));
}
function miLadder() {
  return `<div class="mi-ladder">${MI_RUNGS.map((v, k) => k).reverse().map(k => `<div class="mi-rung ${k === miG.i ? 'on' : ''} ${k < miG.i ? 'done' : ''} ${MI_SAFE.includes(k) ? 'safe' : ''}">
    <span class="n">${k + 1}</span><span class="v">${MI_SAFE.includes(k) ? '⭐ ' : ''}${miFmt(MI_RUNGS[k])}</span></div>`).join('')}</div>`;
}
function miRender(extra = '') {
  const q = miQ(miG.qs[miG.i]), u = miG.used, busy = miG.phase !== 'q';
  const life = (k, ic, t) => `<button class="mi-life ${u[k] ? 'used' : ''}" ${u[k] || busy ? 'disabled' : ''} onclick="miLife('${k}')" title="${t}"><span>${ic}</span><small>${t}</small></button>`;
  const opt = k => {
    const hid = miG.hidden.includes(k);
    let cls = '';
    if (miG.sel === k) cls = 'sel';
    if (miG.phase === 'reveal' || miG.phase === 'end') { if (k === q.a) cls = 'right'; else if (miG.sel === k) cls = 'wrong'; }
    return `<button class="mi-opt ${cls} ${hid ? 'gone' : ''}" style="animation-delay:${.15 + k * .25}s" ${hid || busy && miG.phase !== 'confirm' ? 'disabled' : ''} onclick="miChoose(${k})">
      <span class="mi-l">${MI_L[k]}</span><span class="mi-o">${hid ? '' : miE(q.o[k])}</span></button>`;
  };
  const safeNow = miSafePts();
  miShow(`<div class="mi-stage">
    <div class="mi-main">
      <div class="mi-bar">
        <div class="mi-lifes">${life('h', '✂️', '50:50')}${life('p', '📊', 'Público')}${life('c', '📞', 'Llamada')}</div>
        <button class="mi-walk" ${busy || miG.i === 0 ? 'disabled' : ''} onclick="miWalk()">🛑 Plantarse con ${miFmt(miG.i ? MI_RUNGS[miG.i - 1] : 0)}</button>
      </div>
      <div class="mi-now"><span>${miE(miG.name)}</span> · Pregunta <b>${miG.i + 1}</b> de 10 · por <b>${miFmt(MI_RUNGS[miG.i])}</b> puntos
        <span class="mi-safe-now">${safeNow ? '⭐ asegurados: ' + miFmt(safeNow) : ''}</span></div>
      <div class="mi-dots">${MI_RUNGS.map((v, k) => `<i class="${k < miG.i ? 'done' : ''} ${k === miG.i ? 'on' : ''} ${MI_SAFE.includes(k) ? 'safe' : ''}"></i>`).join('')}</div>
      <div class="mi-q"><span class="mi-cat">${miE(q.cat)}</span><div class="mi-qt">${miE(q.q)}</div>
        <button class="mi-rep" onclick="miSay('${q.id}:q', '')" title="Repetir">🔁</button></div>
      <div class="mi-opts">${[0, 1, 2, 3].map(opt).join('')}</div>
      <div id="mi-extra">${extra}</div>
    </div>
    ${miLadder()}
  </div>`);
}
function miSafePts() { let s = 0; MI_SAFE.forEach(k => { if (miG.i > k) s = MI_RUNGS[k]; }); return s; }

function miChoose(k) {
  if (!(miG.phase === 'q' || miG.phase === 'confirm') || miG.hidden.includes(k)) return;
  miStop(); miSfx('lock');
  miG.sel = k; miG.phase = 'confirm';
  miRender(`<div class="mi-confirm"><div>¿<b>${MI_L[k]}</b> es tu respuesta final?</div>
    <div class="mi-row"><button class="mi-go" onclick="miFinal()">¡Sí, final! 🔒</button><button class="mi-ghost" onclick="miUnsure()">Lo pienso más</button></div></div>`);
  miLine('final');
}
function miUnsure() { miStop(); miG.sel = null; miG.phase = 'q'; miRender(); }
function miFinal() {
  const q = miQ(miG.qs[miG.i]);
  miG.phase = 'lock'; miStop();
  miRender(`<div class="mi-wait">🔒 Respuesta ${MI_L[miG.sel]} bloqueada…</div>`);
  miSfx('tense');
  miLater(() => miReveal(q), 1600 + miG.i * 220);
}
function miReveal(q) {
  const ok = miG.sel === q.a;
  miG.phase = 'reveal';
  const last = miG.i === 9;
  if (ok) {
    miSfx(last ? 'win' : 'ok');
    const safe = MI_SAFE.includes(miG.i);
    miRender(`<div class="mi-fact ok"><div class="mi-verdict">✅ ¡Correcto! ${last ? '' : '+' + miFmt(MI_RUNGS[miG.i])}</div>
      <div class="mi-dato">💡 ${miE(q.dato)}</div>
      ${safe ? `<div class="mi-safe-msg">⭐ ¡Escalón seguro! ${miFmt(MI_RUNGS[miG.i])} puntos ya son tuyos.</div>` : ''}
      <div class="mi-row"><button class="mi-go" onclick="${last ? 'miEnd(\'top\')' : 'miNext()'}">${last ? '¡Ver el premio! 🏆' : 'Siguiente pregunta ▶'}</button></div></div>`);
    miLine(last ? 'millon' : safe ? 'seguro' : 'ok' + (1 + miG.i % 3), () => miSay(q.id + ':d', q.dato));
  } else {
    miSfx('bad');
    miRender(`<div class="mi-fact bad"><div class="mi-verdict">❌ ¡Oh, no! Era la <b>${MI_L[q.a]}</b>: ${miE(q.o[q.a])}</div>
      <div class="mi-dato">💡 ${miE(q.dato)}</div>
      <div class="mi-row"><button class="mi-go" onclick="miEnd('fail')">Ver resultado ▶</button></div></div>`);
    miLine('mal', () => miSay(q.id + ':d', q.dato));
  }
}
function miNext() { miStop(); miClear(); miG.i++; miAsk(); }

// ---------- lifelines ----------
function miLife(k) {
  if (miG.phase !== 'q' || miG.used[k]) return;
  const q = miQ(miG.qs[miG.i]); miG.used[k] = true; miStop();
  if (k === 'h') {
    const wrong = [0, 1, 2, 3].filter(i => i !== q.a).sort(() => Math.random() - .5);
    miG.hidden = wrong.slice(0, 2); miSfx('whoosh'); miRender(); miLine('mitad');
  } else if (k === 'p') {
    const vis = [0, 1, 2, 3].filter(i => !miG.hidden.includes(i));
    let pc = Math.round(Math.max(32, Math.min(92, 90 - (q.l - 1) * 5.5 + (Math.random() * 16 - 8)) + (vis.length === 2 ? 10 : 0)));
    pc = Math.min(pc, 95);
    const others = vis.filter(i => i !== q.a), w = others.map(() => Math.random() + .2), ws = w.reduce((a, b) => a + b, 0);
    const res = [0, 0, 0, 0]; res[q.a] = pc; let left = 100 - pc;
    others.forEach((i, j) => { const v = j === others.length - 1 ? left : Math.round((100 - pc) * w[j] / ws); res[i] = v; left -= v; });
    miG.poll = res;
    miRender(`<div class="mi-poll"><div class="mi-h">📊 El público ha votado</div><div class="mi-bars">${[0, 1, 2, 3].map(i => `<div class="mi-bc">
      <div class="mi-bv">${miG.hidden.includes(i) ? '' : res[i] + '%'}</div><div class="mi-bt"><div class="mi-bf" style="--h:${res[i]}%"></div></div><div class="mi-bl">${MI_L[i]}</div></div>`).join('')}</div>
      <div class="mi-muted">El público no siempre acierta, ¡sobre todo en las difíciles!</div></div>`);
    miLine('publico');
  } else if (k === 'c') {
    miRender(`<div class="mi-call"><div class="mi-h">📞 Llamando a Lola, tu amiga que lo sabe casi todo…</div><div class="mi-ringing">☎️ ring… ring…</div></div>`);
    miSfx('ring');
    miLine('llamada', () => {
      let s = 30;
      const draw = () => { const el = document.getElementById('mi-extra'); if (!el || miG.phase !== 'q') return;
        el.innerHTML = `<div class="mi-call"><div class="mi-friend"><span class="mi-av">👩</span><div class="mi-bubble"><b>Lola:</b> «Mmm… ${miE(q.pista)}»</div></div>
          <div class="mi-clock ${s <= 10 ? 'low' : ''}">⏱️ ${s}</div><div class="mi-muted">¿Hay alguien en casa? ¡También puedes preguntarle mientras corre el reloj!</div></div>`;
        if (window.twemoji) twemoji.parse(el, { folder: 'svg', ext: '.svg' }); };
      draw(); miSay(q.id + ':p', q.pista);
      const tick = () => { s--; if (s < 0) { const el = document.getElementById('mi-extra'); if (el && miG.phase === 'q') el.querySelector('.mi-clock').textContent = '⏱️ ¡Se acabó el tiempo!'; return; } draw(); miLater(tick, 1000); };
      miLater(tick, 1000);
    });
  }
}

// ---------- walk away / end ----------
function miWalk() {
  if (miG.phase !== 'q' || !miG.i) return;
  if (!confirm(`¿Plantarte con ${miFmt(MI_RUNGS[miG.i - 1])} puntos?`)) return;
  miEnd('walk');
}
function miEnd(how) {
  miStop(); miClear();
  const q = miQ(miG.qs[miG.i]);
  const pts = how === 'top' ? MI_RUNGS[9] : how === 'walk' ? MI_RUNGS[miG.i - 1] : miSafePts();
  miG.phase = 'end';
  const st = miState();
  st.games++; st.records.push({ name: miG.name, pts, date: new Date().toISOString().slice(0, 10) });
  st.records = st.records.sort((a, b) => b.pts - a.pts).slice(0, 20);
  const asked = miG.qs.slice(0, how === 'walk' ? miG.i : miG.i + 1);
  st.seen = [...new Set([...st.seen, ...asked])];
  if (st.seen.length >= MI_BANK.length) st.seen = [];     // seen them all: start over
  save();
  const big = pts >= 50000, msg = how === 'top' ? '¡ERES MILLONARIO DE PUNTOS!' : how === 'walk' ? 'Te plantaste a tiempo. ¡Muy listo!' : pts ? 'Te quedas con los puntos del escalón seguro.' : '¡La próxima vez llegas más lejos!';
  miShow(`<div class="mi-end ${how === 'top' ? 'top' : ''}">
    ${how === 'top' || big ? '<div class="mi-confetti">' + Array.from({ length: 40 }, (_, i) => `<i style="left:${Math.random() * 100}%;animation-delay:${Math.random() * 2}s;background:hsl(${Math.random() * 360},90%,60%)"></i>`).join('') + '</div>' : ''}
    <div class="mi-end-e">${how === 'top' ? '🏆' : pts ? '🎉' : '💪'}</div>
    <div class="mi-end-n">${miE(miG.name)}</div>
    <div class="mi-end-p">${miFmt(pts)}<small> puntos</small></div>
    <div class="mi-end-m">${msg}</div>
    ${how === 'walk' ? `<div class="mi-muted">La respuesta de la pregunta ${miG.i + 1} era la <b>${MI_L[q.a]}</b>: ${miE(q.o[q.a])}</div>` : ''}
    <div class="mi-row"><button class="mi-go" onclick="openMi()">Jugar otra vez 🔄</button><button class="mi-ghost" onclick="miClose()">Salir</button></div>
  </div>`);
  if (how === 'walk') miLine('planto'); else if (how === 'top') miSfx('win');
}

